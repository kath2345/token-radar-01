// Token Radar model (radar-2): snapshot in, ranked board out.
//
// The board ranks pre-token protocols by what a token would be worth if the
// protocol's record stayed as it is. Every number comes from the snapshot
// itself; no protocol name is ever special-cased.
//
//   multiple  = the market's own yardstick: the median market-cap / TVL of
//               live-token protocols in the same category (at least 3 of
//               them), clamped to [0.05, 1.0]; the whole market's median when
//               a category has too few live names to trust, or none at all.
//   base      = tvl_usd x multiple
//   growth    = 1 + clamp(change_7d, -40, 60) / 100 x 0.6
//   maturity  = 0.70 + min(age_days, 1095) / 1095 x 0.30
//               (age unknown: 365 days; a protocol that survived years with
//               no token has a steadier claim than a month-old one)
//   reach     = 1 + min(chains - 1, 10) x 0.02
//   implied   = max(1, round(base x growth x maturity x reach))
//
// The board covers the whole watchlist (the floor, never the ceiling) plus
// every other pre-token protocol below the floor that passes the watchlist's
// own exclusion rule (not a bridge, liquid-staking, restaking or CEX product,
// not a versioned pool, no wrapped/staked word in the name, no exchange
// prefix). Live-token protocols are never ranked: they appear apart, at the
// market's own values, so the board never mixes a traded token with a launch
// that has not happened.

/** One protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, stated on the dashboard. */
export interface ModelConstants {
  multiple_floor: number;
  multiple_cap: number;
  min_live_for_category: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  reach_per_chain: number;
  reach_max_chains: number;
}

export const MODEL: ModelConstants = {
  multiple_floor: 0.05,
  multiple_cap: 1.0,
  min_live_for_category: 3,
  growth_weight: 0.6,
  growth_floor: -40,
  growth_cap: 60,
  maturity_floor: 0.7,
  maturity_range: 0.3,
  maturity_days: 1095,
  unknown_age_days: 365,
  reach_per_chain: 0.02,
  reach_max_chains: 10,
};

